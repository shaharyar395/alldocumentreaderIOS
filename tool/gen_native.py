# Generates lib/native/{native_colors,native_drawables,native_shapes}.dart from the
# untouched Android app's res/ (colors.xml light+night, res/drawable/*.xml).
import re, glob, os, xml.etree.ElementTree as ET
RES = "/home/claude/AllDocumentReader/app/src/main/res"
OUT = "/home/claude/AllDocumentReader-Flutter/lib/native"
A = "{http://schemas.android.com/apk/res/android}"
os.makedirs(OUT, exist_ok=True)

def camel(name):
    parts = re.split(r'[_.]', name)
    s = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    if s[0].isdigit(): s = 'n' + s
    if s in ('switch','default','class','new','is','in','for','do','if','else','case','const','final','var','void','null','true','false','this','super','with','try','catch','return','enum'): s += '_'
    return s

def hexcol(v):
    h = v.lstrip('#')
    if len(h) == 3: h = 'FF' + ''.join(c*2 for c in h)
    elif len(h) == 4: h = ''.join(c*2 for c in h)
    elif len(h) == 6: h = 'FF' + h
    return '0x' + h.upper()

# ---------------- colours ----------------
def load_colors(path):
    out = {}
    if not os.path.exists(path): return out
    for c in ET.parse(path).getroot().findall('color'):
        out[c.get('name')] = (c.text or '').strip()
    return out
light = load_colors(f"{RES}/values/colors.xml")
night = load_colors(f"{RES}/values-night/colors.xml")
def resolve(v, table, depth=0):
    if v.startswith('@color/'):
        n = v[7:]
        return resolve(table.get(n, light.get(n, '#FF000000')), table, depth+1)
    if v.startswith('@android:color/'):
        return {'white':'#FFFFFFFF','black':'#FF000000','transparent':'#00000000'}.get(v.split('/')[1], '#FF000000')
    return v
names = sorted(light)
L = ["// GENERATED by tool/gen_native.py from the native Android app's res/values*/colors.xml.",
     "// Do not edit by hand: every colour of the Android app, light and dark (values-night).",
     "import 'package:flutter/material.dart';", "",
     "/// The Android app's colours (@color/...). NC.of(context) follows the app theme (light / dark).",
     "@immutable", "class NC {", "  const NC._({"]
for n in names: L.append(f"    required this.{camel(n)},")
L.append("  });")
L.append("")
for n in names: L.append(f"  /// @color/{n}\n  final Color {camel(n)};")
L.append("")
for label, table in (('light', light), ('dark', {**light, **night})):
    L.append(f"  static const {label} = NC._(")
    for n in names:
        L.append(f"    {camel(n)}: Color({hexcol(resolve(table[n], table))}),")
    L.append("  );")
    L.append("")
L.append("  static NC of(BuildContext context) => Theme.of(context).brightness == Brightness.dark ? dark : light;")
L.append("")
L.append("  /// Resolves a colour name as written in the Android XML (\"text_primary\").")
L.append("  Color byName(String name) {")
L.append("    switch (name) {")
for n in names: L.append(f"      case '{n}':\n        return {camel(n)};")
L.append("      default:\n        return const Color(0xFF000000);")
L.append("    }")
L.append("  }")
L.append("}")
open(f"{OUT}/native_colors.dart", "w").write("\n".join(L) + "\n")

def colexpr(v):
    """Dart expression for a colour value inside drawables: NColor.hex(...) or NColor.ref('name')."""
    if v is None: return None
    v = v.strip()
    if v.startswith('@color/'): return f"NColor.ref('{v[7:]}')"
    if v.startswith('@android:color/'):
        return "NColor.hex(" + hexcol(resolve(v, light)) + ")"
    if v.startswith('?'): return "NColor.ref('icon_main')"
    return "NColor.hex(" + hexcol(v) + ")"

def fnum(v, default=None):
    if v is None: return default
    v = v.replace('dp','').replace('dip','').replace('sp','').replace('px','')
    try: return float(v)
    except: return default

# ---------------- vector drawables ----------------
D = ["// GENERATED by tool/gen_native.py from the native Android app's res/drawable/*.xml vectors.",
     "// Do not edit by hand. Draw with NativeIcon(ND.icXxx, size: 24) (lib/native/native_icon.dart).",
     "import 'dart:ui' show Offset, StrokeCap, StrokeJoin;", "",
     "import 'native_icon.dart';", "",
     "/// Every vector drawable of the Android app (`res/drawable/<name>.xml` → `ND.<camelName>`).",
     "abstract final class ND {"]
shapes = []
count = 0
def node_dart(el, ind):
    out = []
    for ch in el:
        tag = ch.tag
        if tag == 'path':
            a = ch.attrib
            args = ["'" + a.get(A+'pathData','').replace('\n',' ').replace("'", "") + "'"]
            fill = a.get(A+'fillColor'); stroke = a.get(A+'strokeColor')
            grad_stroke = grad_fill = None
            for attr in ch.findall('{http://schemas.android.com/aapt}attr'):
                g = attr.find('gradient')
                if g is None: continue
                ga = g.attrib
                gexpr = (f"NGradient(start: Offset({fnum(ga.get(A+'startX'),0)}, {fnum(ga.get(A+'startY'),0)}), "
                         f"end: Offset({fnum(ga.get(A+'endX'),0)}, {fnum(ga.get(A+'endY'),0)}), "
                         f"colors: [{colexpr(ga.get(A+'startColor'))}, {colexpr(ga.get(A+'endColor'))}])")
                if attr.get('name') == 'android:strokeColor': grad_stroke = gexpr
                else: grad_fill = gexpr
            if fill and fill.strip() not in ('#00000000', '@android:color/transparent'): args.append(f"fill: {colexpr(fill)}")
            if grad_fill: args.append(f"fillGradient: {grad_fill}")
            if stroke: args.append(f"stroke: {colexpr(stroke)}")
            if grad_stroke: args.append(f"strokeGradient: {grad_stroke}")
            if (stroke or grad_stroke):
                sw = fnum(a.get(A+'strokeWidth'), 0.0)
                args.append(f"strokeWidth: {sw}")
                cap = a.get(A+'strokeLineCap'); join = a.get(A+'strokeLineJoin')
                if cap: args.append(f"cap: StrokeCap.{ {'butt':'butt','round':'round','square':'square'}[cap] }")
                if join: args.append(f"join: StrokeJoin.{ {'miter':'miter','round':'round','bevel':'bevel'}[join] }")
            fa = a.get(A+'fillAlpha'); sa = a.get(A+'strokeAlpha')
            if fa: args.append(f"fillAlpha: {float(fa)}")
            if sa: args.append(f"strokeAlpha: {float(sa)}")
            if a.get(A+'fillType') == 'evenOdd': args.append("evenOdd: true")
            out.append(ind + "NPath(" + ", ".join(args) + "),")
        elif tag == 'group':
            a = ch.attrib
            args = []
            for k, nm in (('translateX','tx'),('translateY','ty'),('scaleX','sx'),('scaleY','sy'),('rotation','rotation'),('pivotX','px'),('pivotY','py')):
                if a.get(A+k) is not None: args.append(f"{nm}: {fnum(a.get(A+k))}")
            out.append(ind + "NGroup(" + (", ".join(args) + ", " if args else "") + "children: [")
            out += node_dart(ch, ind + "  ")
            out.append(ind + "]),")
    return out

for f in sorted(glob.glob(f"{RES}/drawable/*.xml")):
    name = os.path.basename(f)[:-4]
    try: root = ET.parse(f).getroot()
    except Exception: continue
    if root.tag == 'vector':
        a = root.attrib
        w = fnum(a.get(A+'width'), 24); h = fnum(a.get(A+'height'), 24)
        vw = fnum(a.get(A+'viewportWidth'), w); vh = fnum(a.get(A+'viewportHeight'), h)
        D.append(f"  /// res/drawable/{name}.xml ({w:g} x {h:g} dp)")
        D.append(f"  static const {camel(name)} = NDrawable(width: {w}, height: {h}, viewportWidth: {vw}, viewportHeight: {vh}, children: [")
        D += node_dart(root, "    ")
        D.append("  ]);")
        D.append("")
        count += 1
    else:
        shapes.append((name, root))
D.append("}")
open(f"{OUT}/native_drawables.dart", "w").write("\n".join(D) + "\n")

# ---------------- shapes (backgrounds) ----------------
S = ["// GENERATED by tool/gen_native.py from the native Android app's res/drawable/*.xml shapes,",
     "// selectors (default state), ripples (their content) and layer-lists (first shape).",
     "// Do not edit by hand. Use: decoration: NS.bgSearch(context)",
     "import 'package:flutter/material.dart';", "", "import 'native_colors.dart';", "",
     "/// Background drawables of the Android app as Flutter decorations.",
     "abstract final class NS {"]
def color_dart(v):
    if v is None: return None
    v = v.strip()
    if v.startswith('@color/'): return f"c.{camel(v[7:])}"
    if v.startswith('@android:color/'): return f"const Color({hexcol(resolve(v, light))})"
    return f"const Color({hexcol(v)})"
def shape_expr(sh):
    a = sh.attrib
    kind = a.get(A+'shape', 'rectangle')
    parts = []
    solid = sh.find('solid'); stroke = sh.find('stroke'); corners = sh.find('corners'); grad = sh.find('gradient')
    if solid is not None and solid.get(A+'color'): parts.append(f"color: {color_dart(solid.get(A+'color'))}")
    if grad is not None:
        ga = grad.attrib
        cols = [color_dart(ga.get(A+k)) for k in ('startColor','centerColor','endColor') if ga.get(A+k)]
        if ga.get(A+'type') == 'radial':
            parts.append(f"gradient: RadialGradient(colors: [{', '.join(cols)}])")
        else:
            ang = int(fnum(ga.get(A+'angle'), 0)) % 360
            al = {0:('Alignment.centerLeft','Alignment.centerRight'),90:('Alignment.bottomCenter','Alignment.topCenter'),
                  180:('Alignment.centerRight','Alignment.centerLeft'),270:('Alignment.topCenter','Alignment.bottomCenter'),
                  45:('Alignment.bottomLeft','Alignment.topRight'),135:('Alignment.bottomRight','Alignment.topLeft'),
                  225:('Alignment.topRight','Alignment.bottomLeft'),315:('Alignment.topLeft','Alignment.bottomRight')}.get(ang,('Alignment.centerLeft','Alignment.centerRight'))
            parts.append(f"gradient: LinearGradient(begin: {al[0]}, end: {al[1]}, colors: [{', '.join(cols)}])")
    if stroke is not None:
        parts.append(f"border: Border.all(color: {color_dart(stroke.get(A+'color')) or 'c.divider'}, width: {fnum(stroke.get(A+'width'),1)})")
    if kind == 'oval':
        parts.append("shape: BoxShape.circle")
    elif corners is not None:
        ca = corners.attrib
        r = fnum(ca.get(A+'radius'))
        tl = fnum(ca.get(A+'topLeftRadius'), r or 0); tr = fnum(ca.get(A+'topRightRadius'), r or 0)
        bl = fnum(ca.get(A+'bottomLeftRadius'), r or 0); br = fnum(ca.get(A+'bottomRightRadius'), r or 0)
        if tl == tr == bl == br:
            if tl: parts.append(f"borderRadius: BorderRadius.circular({tl})")
        else:
            parts.append(f"borderRadius: const BorderRadius.only(topLeft: Radius.circular({tl}), topRight: Radius.circular({tr}), bottomLeft: Radius.circular({bl}), bottomRight: Radius.circular({br}))")
    return "BoxDecoration(" + ", ".join(parts) + ")"
def find_shape(root):
    if root.tag == 'shape': return root
    if root.tag == 'selector':
        items = root.findall('item')
        # Android picks the first item matching the normal state (enabled, not pressed/selected/checked/focused)
        def normal(it):
            for k, v in it.attrib.items():
                if not k.startswith(A+'state_'): continue
                st = k[len(A)+6:]
                want = 'true' if st in ('enabled', 'window_focused') else 'false'
                if v != want: return False
            return True
        default = [i for i in items if normal(i)][:1] or items[-1:]
        for it in default:
            s = it.find('shape')
            if s is not None: return s
            d = it.get(A+'drawable')
            if d and d.startswith('@drawable/'):
                p = f"{RES}/drawable/{d[10:]}.xml"
                if os.path.exists(p): return find_shape(ET.parse(p).getroot())
        return None
    if root.tag == 'ripple':
        for it in root.findall('item'):
            if it.get(A+'id') == '@android:id/mask': continue
            s = it.find('shape')
            if s is not None: return s
            d = it.get(A+'drawable')
            if d and d.startswith('@drawable/'):
                p = f"{RES}/drawable/{d[10:]}.xml"
                if os.path.exists(p): return find_shape(ET.parse(p).getroot())
        return None
    if root.tag == 'layer-list':
        for it in root.findall('item'):
            s = it.find('shape')
            if s is not None: return s
    return None
scount = 0
for name, root in shapes:
    sh = find_shape(root)
    if sh is None: continue
    S.append(f"  /// res/drawable/{name}.xml ({root.tag})")
    S.append(f"  static BoxDecoration {camel(name)}(BuildContext context) {{")
    expr = shape_expr(sh)
    if 'c.' in expr: S.append("    final c = NC.of(context);")
    S.append(f"    return {expr};")
    S.append("  }")
    S.append("")
    scount += 1
S.append("}")
open(f"{OUT}/native_shapes.dart", "w").write("\n".join(S) + "\n")
print("colors", len(names), "vectors", count, "shapes", scount, "of", len(shapes))
